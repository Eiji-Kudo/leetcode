// 元のステップで学んだ概念:
// - for (let i = 0; i < arr.length; i++) の基本形
// - インデックス i で要素にアクセス (arr[i])
// - ループ内で i を計算に使う（インデックスそのものが情報になる）

// =============================================
// 復習問題: 要素とインデックスの積の合計
//
// 数値の配列を受け取り、各要素とそのインデックスの積の合計を返してください。
// つまり arr[0]*0 + arr[1]*1 + arr[2]*2 + ... の総和。
//
// 例: [10, 20, 30] → 10*0 + 20*1 + 30*2 = 0 + 20 + 60 = 80
//     [1, 2, 3, 4] → 1*0 + 2*1 + 3*2 + 4*3 = 0 + 2 + 6 + 12 = 20
// 空配列の場合は 0 を返してください。
// =============================================

function weightedIndexSum(arr) {
  // TODO: ここに実装を書いてください
    return arr.reduce((total, val, index) => total + val * index, 0);
    
}

// --- テスト ---
console.assert(weightedIndexSum([10, 20, 30]) === 80, "テスト1 失敗");
console.assert(weightedIndexSum([1, 2, 3, 4]) === 20, "テスト2 失敗");
console.assert(weightedIndexSum([5]) === 0, "テスト3 失敗: 要素1つ");
console.assert(weightedIndexSum([]) === 0, "テスト4 失敗: 空配列");
console.assert(weightedIndexSum([-1, -2, -3]) === -8, "テスト5 失敗: 負の数");

