// =============================================
// 問題: 数値の配列を受け取り、配列の中で最も大きい値を返してください。
// 配列が空の場合は null を返してください。
// =============================================

function findMax(numbers) {
  // TODO: ここに実装を書いてください
    // 配列の最大値を求める


    if (Array.isArray(numbers) && numbers.length === 0)
            return null;
    else {
        return Math.max(...numbers);
    }
}

// --- テスト ---
console.assert(findMax([3, 1, 4, 1, 5]) === 5, "テスト1 失敗");
console.assert(findMax([-10, -3, -20]) === -3, "テスト2 失敗");
console.assert(findMax([42]) === 42, "テスト3 失敗");
console.assert(findMax([]) === null, "テスト4 失敗");

