// 1週間の売上金額の配列を受け取り、最も大きい売上金額を返してください。
// 配列が空の場合は null を返してください。

function findPeakSale(sales) {
  // TODO: ここに実装を書いてください
    //
    if (sales.length == 0) return null;
    const ans = Math.max(...sales);
    return ans;
}

// --- テスト ---
console.assert(findPeakSale([1200, 850, 1430, 990]) === 1430, "テスト1 失敗");
console.assert(findPeakSale([500]) === 500, "テスト2 失敗");
console.assert(findPeakSale([-10, -25, -3]) === -3, "テスト3 失敗");
console.assert(findPeakSale([]) === null, "テスト4 失敗");

